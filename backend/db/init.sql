-- ===========================================================
-- Cardio Insights - MySQL initialization script
-- Creates the incc schema and seeds sample data.
-- Also creates the metabase_app_db database used by Metabase
-- to store its own configuration.
-- ===========================================================

CREATE DATABASE IF NOT EXISTS metabase_app_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

GRANT ALL PRIVILEGES ON metabase_app_db.* TO 'cardio'@'%';

USE incc;

-- -----------------------------------------------------------
-- Users & permissions
-- -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS use_usuariostipo (
    k_id    INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
    Descr   VARCHAR(50)  NOT NULL
);

CREATE TABLE IF NOT EXISTS use_usuarios (
    k_id    INT           NOT NULL AUTO_INCREMENT PRIMARY KEY,
    Alias   VARCHAR(50)   NOT NULL,
    Noms    VARCHAR(100),
    Apes    VARCHAR(100),
    Clave   VARCHAR(100),
    MD5text VARCHAR(100),
    IdTipo  INT,
    Activo  TINYINT(1)    DEFAULT 1,
    k_del   TINYINT(1)    DEFAULT 0,
    FOREIGN KEY (IdTipo) REFERENCES use_usuariostipo(k_id)
);

CREATE TABLE IF NOT EXISTS use_permisoaccion (
    k_id    INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
    Descr   VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS use_permiso (
    k_id            INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
    IdUsuario       INT          NOT NULL,
    IdPermisoAccion INT,
    Si              TINYINT(1)   DEFAULT 1,
    k_del           TINYINT(1)   DEFAULT 0,
    Descr           VARCHAR(100),
    FOREIGN KEY (IdUsuario)       REFERENCES use_usuarios(k_id),
    FOREIGN KEY (IdPermisoAccion) REFERENCES use_permisoaccion(k_id)
);

-- -----------------------------------------------------------
-- Procedure coordination (shared by surgery and PTCA)
-- -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS flow_coordina (
    Cod                   INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
    FechaCoordina         DATE,
    FechaRealizado        DATE,
    FechaEgreso           DATE,
    FechaInput            DATE,
    FechaInputTramite     DATE,
    FechaFinTramite       DATE,
    Observaciones         VARCHAR(500),
    Realizado             SMALLINT     DEFAULT 255,
    Autorizado            SMALLINT     DEFAULT 255,
    EdadCoo               INT,
    CodPac                INT,
    CodSeguroCoo          INT          DEFAULT 0,
    CodCoordinaReglaMotivo INT,
    CodActo               INT,
    sTecnica              VARCHAR(10)
);

-- -----------------------------------------------------------
-- Surgery
-- -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS dat_cirugia (
    k_id          INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CodCoordina   INT  NOT NULL,
    POestadiaUCI  DECIMAL(6,2),
    FOREIGN KEY (CodCoordina) REFERENCES flow_coordina(Cod)
);

-- -----------------------------------------------------------
-- PTCA (percutaneous transluminal coronary angioplasty)
-- -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS call_ptcamaster (
    Cod           INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CodCoordina   INT  NOT NULL,
    FOREIGN KEY (CodCoordina) REFERENCES flow_coordina(Cod)
);

-- -----------------------------------------------------------
-- Clinical outcomes (mortality, readmissions)
-- -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS flow_procedimientocardiologia (
    k_id          INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
    FechaEgreso   DATE,
    FechaFallece  DATE,
    CodCoordina   INT,
    FOREIGN KEY (CodCoordina) REFERENCES flow_coordina(Cod)
);

CREATE TABLE IF NOT EXISTS sqlsalud_fallece (
    NroHistoria INT,
    Fecha       DATETIME,
    IdTipo      INT,
    Tipo        VARCHAR(100),
    Nota        VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS stk_cartera (
    CodPacFichaCubre INT NOT NULL,
    Nombre           VARCHAR(100)
);

